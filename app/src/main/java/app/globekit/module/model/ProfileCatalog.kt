    val defaultRegion: RegionProfile = regions.first { it.id == "jp-tokyo" }

    fun findRegion(id: String?): RegionProfile =
        regions.firstOrNull { it.id == id } ?: defaultRegion

    fun findCarrier(region: RegionProfile, id: String?): CarrierProfile =
        region.carriers.firstOrNull { it.id == id } ?: region.carriers.first()

    private fun region(
        id: String,
        name: String,
        countryIso: String,
        localeTag: String,
        timeZoneId: String,
        latitude: Double,
        longitude: Double,
        vararg carriers: CarrierProfile,
    ) = RegionProfile(id, name, countryIso, localeTag, timeZoneId, latitude, longitude, carriers.toList())

    private fun carrier(id: String, name: String, mcc: String, mnc: String) =
        CarrierProfile(id, name, mcc, mnc)
